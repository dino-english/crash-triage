#!/usr/bin/env bash
# 归一化：抹掉两次跑批之间必然不同的字段，让等价性 diff 有意义（design D7）。
#
# 直接 diff 一定不为空——run_id / last_run / 幂等键 / 取数区间时刻每次都变。
# 归一化只替换**具体时刻**，保留**格式**：格式变了正是要抓的回归。
#
# 用法：normalize.sh <文件>  → 归一化后的内容到 stdout
set -uo pipefail
f="${1:?用法：normalize.sh <文件>}"
[ -f "$f" ] || exit 0

sed -E \
  -e 's/[0-9]{8}-[0-9]{6}(-resend-[0-9]{6})?/<RUNID>/g' \
  -e 's/[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z/<ISO8601>/g' \
  -e 's/[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2} UTC/<TS_UTC>/g' \
  -e 's/[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}/<MMDD_HHMM>/g' \
  -e 's#/runs/[0-9]{4}-[0-9]{2}-[0-9]{2}/L[12]/[0-9]{8}-[0-9]{6}/#/runs/<DAY>/<LVL>/<RUNID>/#g' \
  -e 's/[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}/<DATE_HHMM>/g' \
  "$f"
